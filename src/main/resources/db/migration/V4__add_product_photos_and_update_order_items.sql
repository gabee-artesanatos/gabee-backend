    ADD COLUMN photo_caption TEXT;


-- Permite produtos iguais com personalizações diferentes

ALTER TABLE order_items
DROP CONSTRAINT unique_order_items_order_product;


-- Permite o status CANCELED

ALTER TABLE orders
DROP CONSTRAINT check_orders_status;

ALTER TABLE orders
    ADD CONSTRAINT check_orders_status
        CHECK (status IN (
                          'PENDING',
                          'CONFIRMED',
                          'IN_PROGRESS',
                          'COMPLETED',
                          'SENT',
                          'DELIVERED',
                          'CANCELED'
            ));


-- Cria a tabela de fotos

CREATE TABLE photos
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    photo_path    TEXT NOT NULL,
    order_item_id BIGINT NOT NULL,
    order_photo   INTEGER,

    CONSTRAINT fk_photos_order_item
        FOREIGN KEY (order_item_id)
            REFERENCES order_items (id),

    CONSTRAINT check_photos_path
        CHECK (LENGTH(TRIM(photo_path)) > 0),

    CONSTRAINT check_photos_order
        CHECK (order_photo >= 0)
);


-- Índice para consultas das fotos por item

CREATE INDEX idx_photos_order_item_id
    ON photos (order_item_id);
