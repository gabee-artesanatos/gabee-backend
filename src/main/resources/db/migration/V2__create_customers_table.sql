CREATE TABLE customers
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT        NOT NULL,
    cpf          VARCHAR(11) NOT NULL UNIQUE,
    phone        TEXT        NOT NULL,
    email        TEXT        NOT NULL UNIQUE,
    birthday     DATE,
    gender       TEXT,
    cep          TEXT        NOT NULL,
    street       TEXT        NOT NULL,
    number       TEXT        NOT NULL,
    complement   TEXT,
    neighborhood TEXT        NOT NULL,
    city         TEXT        NOT NULL,
    state        TEXT        NOT NULL,
    active       boolean     NOT NULL DEFAULT TRUE,

    CONSTRAINT check_customers_name
        CHECK (length(trim(name)) > 0),

    CONSTRAINT check_customers_cpf
        CHECK (cpf ~ '^[0-9]{11}$'),

    CONSTRAINT check_customers_phone
        CHECK (length(trim(phone)) > 0),

    CONSTRAINT check_customers_email
        CHECK (length(trim(email)) > 0),

    CONSTRAINT check_customers_gender
        CHECK (length(trim(gender)) > 0),

    CONSTRAINT check_customers_cep
        CHECK (length(trim(cep)) > 0),

    CONSTRAINT check_customers_street
        CHECK (length(trim(street)) > 0),


    CONSTRAINT check_customers_number
        CHECK (length(trim(number)) > 0),

    CONSTRAINT check_customers_neighborhood
        CHECK (length(trim(neighborhood)) > 0),

    CONSTRAINT check_customers_city
        CHECK (length(trim(city)) > 0),

    CONSTRAINT check_customers_state
        CHECK (length(trim(state)) > 0)
);